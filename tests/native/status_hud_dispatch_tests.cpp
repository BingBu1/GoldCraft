    globals.time+=2;ExpireStatusHud();
    check(messages.size()==5&&messages.back().empty(),"Expired stream left stale text");
    ExpireStatusHud();HandleStatusHud(packet(8,false));
    check(messages.size()==5,"Expired empty stream erased unrelated HUD twice");
    HandleStatusHud(packet(9,true));link.online=false;ExpireStatusHud();
    check(messages.size()==7&&messages.back().empty(),"Disconnected stream left stale text");
    ExpireStatusHud();ClearStatusHud();
    check(messages.size()==7,"Disconnected empty stream repeatedly cleared");
    link.online=true;HandleStatusHud(packet(10,true));ClearStatusHud();
