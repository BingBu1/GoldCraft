void ParserCases()
{
    const std::string both="{\"classname\" \"playerspawn\"}{\"classname\" \"zombiespawn\"}";
    Check(csol::bsp::HasScenarioEntities(both),"actual scenario classnames select profile");
    Check(csol::bsp::HasScenarioEntities("{ classname zombiespawn } { classname info_player_start }"),
        "original early-map player spawn fallback selects scenario profile");
    Check(csol::bsp::HasScenarioEntities("{classname zbstrigger_spawn}{classname zs_safezone}"),
        "actual later-map spawn and safe-zone pair selects scenario profile");
    for(const auto* text:{"", "{}", "{classname worldspawn}", "{classname playerspawn}",
        "{classname zombiespawn}", "{classname info_player_deathmatch}{classname zombiespawn}",
        "{classname zbstrigger_spawn}", "{classname zs_safezone}",
        "{classname worldspawn message zbstrigger_spawn target zs_safezone}",
        "{classname worldspawn message playerspawn target zombiespawn}",
        "// {classname playerspawn}{classname zombiespawn}\n{classname worldspawn}",
        "{classname worldspawn message \"playerspawn zombiespawn\"}",
        "{classname Playerspawn}{classname zombiespawn}",
        "{classname playerspawn classname worldspawn}{classname zombiespawn}",
        "{classname playerspawn}{classname zombiespawn", "{classname playerspawn}{classname}",
        "{classname playerspawn}{classname \"zombiespawn}",
        "{classname playerspawn}{classname zombiespawn} trailing", "{classname {nested} zombiespawn}"})
        Check(!csol::bsp::HasScenarioEntities(text),"text/comment/incomplete/invalid schema cannot select profile");
    Check(csol::bsp::HasScenarioEntities("// leading\n{classname playerspawn}// middle\n{classname zombiespawn}// end"),
        "ordinary line comments do not hide actual entity records");
    Check(csol::bsp::HasScenarioEntities("{classname worldspawn classname playerspawn}{classname zombiespawn}"),
        "last classname follows actual duplicate-key semantics");
    Check(!csol::bsp::HasScenarioEntities(both+"{\"unterminated"),"later malformed entity rejects an otherwise matching prefix");
    for(const auto* name:{"maps/zs_allout1.bsp","MAPS\\ZS_ALLOUT2.BSP","zs_allout3.bsp","maps/zs_electron2.bsp"})
    {
        const auto b=csol::bsp::ScenarioHullForMap(name);
        Check(b.mins==std::array<float,3>{-80,-80,-110}&&b.maxs==std::array<float,3>{80,80,110},"exact original four-map profile");
    }
    const auto multi=csol::bsp::ScenarioHullForMap("maps/zs_multiboss.bsp");
    Check(multi.mins==std::array<float,3>{-72,-72,-72}&&multi.maxs==std::array<float,3>{72,72,72},"exact multiboss profile");
    for(const auto* name:{"maps/zs_deadend.bsp","maps/zs_allout10.bsp","maps/zs_allout1.bsp.bak","maps/cs_assault.bsp","zs_multiboss"})
    {
        const auto b=csol::bsp::ScenarioHullForMap(name);
        Check(b.mins==std::array<float,3>{-40,-40,-90}&&b.maxs==std::array<float,3>{40,40,90},"filename near-match does not select exception");
    }
}
std::vector<unsigned char> Read(const char* path)
{
    std::ifstream file(path,std::ios::binary);
    Require(bool(file),"real BSP opens");
    return {std::istreambuf_iterator<char>(file),std::istreambuf_iterator<char>()};
}
struct Loaded
{
    std::vector<unsigned char> bytes;
    std::string entities;
    model_t world{};
    explicit Loaded(const char* path)
    {
        bytes=Read(path);Require(bytes.size()>=sizeof(dheader_t),"real BSP has header");
        auto* header=reinterpret_cast<dheader_t*>(bytes.data());
        Require(header->version==30,"real GoldSrc BSP30");
        for(const auto& l:header->lumps)
            Require(l.fileofs>=0&&l.filelen>=0&&std::size_t(l.fileofs)+std::size_t(l.filelen)<=bytes.size(),"real lump range is bounded");
        const auto& e=header->lumps[LUMP_ENTITIES];
        entities.assign(reinterpret_cast<const char*>(bytes.data()+e.fileofs),std::size_t(e.filelen));
        std::snprintf(world.name,sizeof(world.name),"%s",path);
        // model_t::name is64 bytes; use the real basename rather than clipping
        // a long host-side fixture path before the exception-map filename.
        const std::string full=path;const auto slash=full.find_last_of("/\\");
        std::snprintf(world.name,sizeof(world.name),"maps/%s",full.substr(slash+1).c_str());
        world.type=mod_brush;world.entities=entities.data();
        loadmodel=&world;mod_base=bytes.data();
        Mod_LoadPlanes(&header->lumps[LUMP_PLANES]);
        Mod_LoadClipnodes(&header->lumps[LUMP_CLIPNODES]);
        Mod_LoadSubmodels(&header->lumps[LUMP_MODELS]);
        Require(world.numsubmodels>0,"real BSP has world model");
        inlineModels.clear();SetupProductionSubmodels(&world);
    }
};
int Query(model_t& model,const float* mins,const float* maxs,const float* worldPoint,
    const float* brushOrigin,std::array<float,3>* observed=nullptr,int* selected=nullptr)
{
    selectedModel=&model;edict_t brush{};brush.v.modelindex=1;
    VectorCopy(brushOrigin,brush.v.origin);
    vec3_t offset,local;
    auto* hull=SV_HullForBsp(&brush,mins,maxs,offset);
    if(observed)*observed={offset[0],offset[1],offset[2]};
    if(selected)*selected=int(hull-model.hulls);
    VectorSubtract(worldPoint,offset,local);
    return SV_HullPointContents(hull,hull->firstclipnode,local);
}
void MapCases(const char* path,bool expectedScenario)
{
    Loaded map(path);auto& model=map.world;
    const bool scenario=csol::bsp::HasScenarioEntities(model.entities);
    Check(scenario==expectedScenario,"real map schema classification");
    const auto expected=csol::bsp::ScenarioHullForMap(model.name);
    for(int axis=0;axis<3;++axis)
    {
        Check(model.hulls[2].clip_mins[axis]==(scenario?expected.mins[axis]:-32)&&
            model.hulls[2].clip_maxs[axis]==(scenario?expected.maxs[axis]:32),"actual Mod_LoadClipnodes applies only selected map profile");
    }
    for(const auto& [name,sub]:inlineModels)
    {
        Check(std::memcmp(sub.hulls[2].clip_mins,model.hulls[2].clip_mins,sizeof(vec3_t))==0&&
            std::memcmp(sub.hulls[2].clip_maxs,model.hulls[2].clip_maxs,sizeof(vec3_t))==0&&
            sub.hulls[2].clipnodes==model.hulls[2].clipnodes&&sub.hulls[2].planes==model.hulls[2].planes,
            "actual brush setup copy inherits profile and collision storage");
        const int index=std::stoi(name.substr(1));
        Check(sub.hulls[2].firstclipnode==model.submodels[index].headnode[2],"inline brush retains its own actual BSP headnode");
    }
    const float zero[3]{},origin[3]{128,-64,32},mins[3]{-55,-55,-32},maxs[3]{55,55,160},point[3]{-484,180,-3224};
    if(std::string(model.name)=="maps/zs_deadend.bsp")
    {
        Require(scenario,"real DeadEnd schema accepted");
        std::array<float,3> offset;
        const int fresh=Query(model,mins,maxs,point,zero,&offset);
        Check(offset==std::array<float,3>{0,0,-58}&&fresh==CONTENTS_EMPTY,"actual production hull fixes real Oberon spawn contents");
        model_t old=model;
        for(int a=0;a<3;++a){old.hulls[2].clip_mins[a]=-32;old.hulls[2].clip_maxs[a]=32;}
        Check(Query(old,mins,maxs,point,zero)==CONTENTS_SOLID,"old ReHLDS hull contract reproduces real spawn SOLID");
        sv_rehlds_hull_centering.value=1;
        Check(Query(old,mins,maxs,point,zero)==CONTENTS_SOLID,"centering-only old hull remains SOLID");
        sv_rehlds_hull_centering.value=0;
        for(const auto& box:BossBoxes)
        {
            const float floorPoint[3]{-484,180,-3264-box.mins[2]+8};
            int hull{};
            Check(Query(model,box.mins.data(),box.maxs.data(),floorPoint,zero,nullptr,&hull)==CONTENTS_EMPTY&&hull==2,
                "each actual catalog large Boss bbox uses corrected hull and leaves arena floor");
        }
    }
    if(!inlineModels.empty())
    {
        auto& sub=inlineModels.begin()->second;
        float localPoint[3]{(sub.mins[0]+sub.maxs[0])/2,(sub.mins[1]+sub.maxs[1])/2,(sub.mins[2]+sub.maxs[2])/2};
        float shifted[3];VectorAdd(localPoint,origin,shifted);
        std::array<float,3> offset;
        const int base=Query(sub,mins,maxs,localPoint,zero);
        Check(Query(sub,mins,maxs,shifted,origin,&offset)==base,"actual inline hull query preserves translated brush origin");
        Check(offset[0]==origin[0]+(scenario?0:23)&&offset[1]==origin[1]+(scenario?0:23),"inline brush uses map profile centering and entity translation");
    }
    for(int centered:{0,1})
    {
        sv_rehlds_hull_centering.value=float(centered);
        std::array<float,3> offset;int hull{};
        Query(model,mins,maxs,point,zero,&offset,&hull);
        Check(hull==2&&offset[0]==(scenario||centered?0:23)&&offset[1]==(scenario||centered?0:23),"ordinary-CS centering cvar remains effective without scenario leakage");
    }
    sv_rehlds_hull_centering.value=0;
    // Reuse the actual model record and inline registry across both schemas.
    const std::string saved=map.entities;
    model.entities=const_cast<char*>("{classname worldspawn}{classname info_player_start}");
    loadmodel=&model;mod_base=map.bytes.data();auto* header=reinterpret_cast<dheader_t*>(mod_base);
    Mod_LoadClipnodes(&header->lumps[LUMP_CLIPNODES]);SetupProductionSubmodels(&model);
    Check(!csol::bsp::IsScenarioLargeHull(model.hulls[2].clip_mins,model.hulls[2].clip_maxs)&&model.hulls[2].clip_mins[2]==-32,
        "actual loader resets a reused model to ordinary CS dimensions on map reload");
    model.entities=map.entities.data();loadmodel=&model;
    Mod_LoadClipnodes(&header->lumps[LUMP_CLIPNODES]);SetupProductionSubmodels(&model);
    Check(csol::bsp::IsScenarioLargeHull(model.hulls[2].clip_mins,model.hulls[2].clip_maxs)==scenario,
        "actual loader reselects schema after ordinary-to-scenario reload");
    std::cout<<"MAP "<<model.name<<" scenario="<<scenario<<" hullZ="<<model.hulls[2].clip_mins[2]
        <<" inline="<<inlineModels.size()<<" nodes="<<model.numclipnodes<<'\n';
}
