def apply(pose, frame, curve):
    for channel, keys in (
        ("root", ROOT),
        ("pelvis", PELVIS),
        ("chest", CHEST),
        ("head", HEAD),
        ("shrug", SHOULDERS),
        ("curl", CURL),
    ):
        pose[channel] += curve(frame, keys)
    pose["grip"] = np.array([curve(frame, keys)[0] for keys in GRIP_WEIGHT])
    for side, keys in enumerate(ARMS):
        pose["hands"][side] += curve(frame, keys)
    return pose
